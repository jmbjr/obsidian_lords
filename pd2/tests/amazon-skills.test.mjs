import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { spawnSync } from "node:child_process";
const run = () => spawnSync(process.execPath, ["pd2/scripts/normalize-amazon-skills.mjs"], { encoding: "utf8" });
let processResult = run();
assert.equal(processResult.status, 0, processResult.stderr);
const path = "pd2/generated/amazon-skills.json";
const first = await readFile(path, "utf8");
const data = JSON.parse(first);
assert.equal(data.source.season, 14);
assert.equal(data.source.commit, "7952f34719aa3a5cb41334a91fe36dbcbdd8be9c");
assert.equal(data.skills.length, 31);
const byId = (id) => data.skills.find((skill) => skill.identity.internalId === id);
assert.equal(byId(12).identity.internalName, "Multiple Shot");
assert.equal(byId(12).selected.requiredLevel, 6);
assert.equal(byId(6).identity.internalName, "Magic Arrow");
assert.match(byId(6).raw.skill.EDmgSymPerCalc, /Guided Arrow/);
assert.equal(byId(26).identity.internalName, "Strafe");
assert.equal(byId(365).identity.internalName, "Shattering Arrow");
assert.ok(data.skills.every((skill) => skill.raw.description && skill.raw.skill && skill.selected.maxLevel === 20));
processResult = run();
assert.equal(processResult.status, 0, processResult.stderr);
assert.equal(await readFile(path, "utf8"), first);
console.log("Native S14 Amazon skill slice passed");
